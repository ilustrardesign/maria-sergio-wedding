import { mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const contentPath = path.join(root, "src/content/wedding.ts");
const outputDir = path.join(root, "public/images/gifts/generated");
const manifestPath = path.join(root, "src/generated/gift-images.ts");
const targetWidths = [400, 600, 800, 1200, 1600];

const sourceText = await readFile(contentPath, "utf8");
const entries = [...sourceText.matchAll(/\{ id: "([^"]+)"[^\n]+image: \{ src: "([^"]+)"/g)].map((match) => ({ id: match[1], source: match[2] }));
if (entries.length === 0) throw new Error("No gift image entries found in wedding.ts");

async function resolveMaster(source) {
  const requested = path.join(root, "public", source);
  try { await stat(requested); return requested; } catch {}
  const dir = path.dirname(requested);
  const stem = path.basename(requested, path.extname(requested));
  const candidates = (await readdir(dir)).filter((name) => path.basename(name, path.extname(name)) === stem && /\.(jpe?g)$/i.test(name));
  if (candidates.length === 1) return path.join(dir, candidates[0]);
  throw new Error(`Master ausente para ${source}`);
}

await rm(outputDir, { recursive: true, force: true });
await mkdir(outputDir, { recursive: true });
await mkdir(path.dirname(manifestPath), { recursive: true });

const manifest = {};
for (const entry of entries) {
  if (!/\.(jpe?g)$/i.test(entry.source)) continue;
  const master = await resolveMaster(entry.source);
  const metadata = await sharp(master).metadata();
  const width = metadata.width ?? 0;
  const height = metadata.height ?? 0;
  if (!width || !height) throw new Error(`Dimensão inválida para ${entry.source}`);
  const ratio = width / height;
  if (Math.abs(ratio - 1.5) > 0.08) console.warn(`Aviso: ${entry.id} está em ${width}×${height} (${ratio.toFixed(3)}), fora de 3:2 aproximado.`);
  const stem = path.basename(entry.source, path.extname(entry.source));
  const variants = [];
  for (const requestedWidth of targetWidths.filter((value) => value <= width)) {
    const outWidth = requestedWidth;
    const outHeight = Math.round(height * outWidth / width);
    const filename = `${stem}-${outWidth}.webp`;
    await sharp(master).resize({ width: outWidth, withoutEnlargement: true }).webp({ quality: 82, lossless: false }).toFile(path.join(outputDir, filename));
    variants.push({ width: outWidth, height: outHeight, src: `/images/gifts/generated/${filename}` });
  }
  const largest = variants.at(-1);
  manifest[entry.source] = { id: entry.id, src: largest.src, srcSet: variants.map((variant) => `${variant.src} ${variant.width}w`).join(", "), width: largest.width, height: largest.height, variants };
}

const generated = `// Generated by scripts/generate-gift-images.mjs — do not edit.\nexport type GiftImageVariant = { width: number; height: number; src: string };\nexport type GiftImage = { id: string; src: string; srcSet: string; width: number; height: number; variants: GiftImageVariant[] };\nexport const giftImages: Record<string, GiftImage> = ${JSON.stringify(manifest, null, 2)};\n`;
await writeFile(manifestPath, generated);
console.log(`Generated ${Object.values(manifest).reduce((total, image) => total + image.variants.length, 0)} WebP variants for ${Object.keys(manifest).length} gifts.`);
