import { copyFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import sharp from "sharp";

const outputDir = path.join("public", "images", "wedding", "venues", "generated");
const masterDir = path.join("public", "images", "wedding", "venues", "masters");
const quality = 87;
const widths = [480, 768, 1024, 1280];
const images = [
  { id: "ceremony", source: "01 - Cerimônia.png", master: "cerimonia-master.png", prefix: "cerimonia" },
  { id: "reception", source: "02 - Recepção.png", master: "recepcao-master.png", prefix: "recepcao" },
];

function publicPath(filePath) {
  return `/${filePath.replaceAll(path.sep, "/").replace(/^public\//, "")}`;
}

await Promise.all([mkdir(outputDir, { recursive: true }), mkdir(masterDir, { recursive: true })]);

const manifest = {};
for (const image of images) {
  const metadata = await sharp(image.source).metadata();
  if (!metadata.width || !metadata.height) throw new Error(`Cannot read dimensions for ${image.source}`);

  const publicMaster = path.join(masterDir, image.master);
  await copyFile(image.source, publicMaster);

  const variants = [];
  for (const width of widths) {
    if (width > metadata.width) continue;
    const output = path.join(outputDir, `${image.prefix}-${width}.webp`);
    await sharp(image.source).resize({ width, withoutEnlargement: true }).webp({ quality, effort: 6 }).toFile(output);
    variants.push({ width, height: Math.round((metadata.height / metadata.width) * width), src: publicPath(output) });
  }

  const fallback = variants.at(-1);
  if (!fallback) throw new Error(`No variants generated for ${image.source}`);
  manifest[image.id] = {
    src: fallback.src,
    srcSet: variants.map((variant) => `${variant.src} ${variant.width}w`).join(", "),
    width: metadata.width,
    height: metadata.height,
    fallbackSrc: publicPath(publicMaster),
    variants,
  };
}

const output = `// Generated by scripts/generate-venue-images.mjs — do not edit.\nexport type VenueImageVariant = { width: number; height: number; src: string };\nexport type VenueImage = { src: string; srcSet: string; width: number; height: number; fallbackSrc: string; variants: VenueImageVariant[] };\nexport const venueImages = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<"ceremony" | "reception", VenueImage>;\n`;
await writeFile(path.join("src", "generated", "venue-images.ts"), output);
console.log(`Generated venue WebP variants at quality ${quality}.`);
